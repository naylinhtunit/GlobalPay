const normalize = (key: string) => key.replace(/\s+/g, " ").trim();
const translations = new Map<string, Record<Language, string>>();
for (const [en, my, ja, ...aliases] of MESSAGES) {
  const value = { en, my, ja };
  for (const key of [en, my, ja, ...aliases]) translations.set(normalize(key), value);
}
export function hasTranslation(key: string) { return translations.has(normalize(key)); }
export function translateText(key: string, language: Language, params: TranslationParams = {}) {
  const message = translations.get(normalize(key))?.[language] ?? key;
  return message.replace(/\{(\w+)\}/g, (match, name) => params[name] === undefined ? match : String(params[name]));
}

/** Built-in shift labels may include saved clock times. Custom labels remain untouched. */
export function localizeShiftLabel(label: string, language: Language) {
  for (const name of ["Morning / မနက်", "Afternoon / နေ့လယ်", "Night / ညဆိုင်း"]) {
    if (label === name || label.startsWith(name + " ")) {
      return translateText(name, language) + label.slice(name.length).replace("(+1 day)", translateText("(+1 day)", language));
    }
  }
  return label;
}
