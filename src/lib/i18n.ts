export type Language = "my" | "en" | "ja";
export type TranslationParams = Record<string, string | number>;
export const LANGUAGE_LOCALES: Record<Language, string> = { my: "my-MM", en: "en-US", ja: "ja-JP" };
export const isLanguage = (value: unknown): value is Language => value === "my" || value === "en" || value === "ja";

/** Some Android WebViews/macOS runtimes fall back to English for my-MM dates. */
export function formatDisplayDate(date: Date, language: Language, options: Intl.DateTimeFormatOptions): string {
  const formatted = new Intl.DateTimeFormat(LANGUAGE_LOCALES[language], options).format(date);
  if (language !== "my") return formatted;
  const words: Record<string, string> = {
    January: "ဇန်နဝါရီ", February: "ဖေဖော်ဝါရီ", March: "မတ်", April: "ဧပြီ", May: "မေ", June: "ဇွန်",
    July: "ဇူလိုင်", August: "ဩဂုတ်", September: "စက်တင်ဘာ", October: "အောက်တိုဘာ", November: "နိုဝင်ဘာ", December: "ဒီဇင်ဘာ",
    Sunday: "တနင်္ဂနွေ", Monday: "တနင်္လာ", Tuesday: "အင်္ဂါ", Wednesday: "ဗုဒ္ဓဟူး", Thursday: "ကြာသပတေး", Friday: "သောကြာ", Saturday: "စနေ",
    Sun: "နွေ", Mon: "လာ", Tue: "ဂါ", Wed: "ဟူး", Thu: "ကြာ", Fri: "သော", Sat: "နေ",
  };
  return formatted.replace(/\b[A-Za-z]+\b/g, word => words[word] || word);
}

